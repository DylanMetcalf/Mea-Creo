// Regenerates src/lib/pdf-assets.ts from the master logo files. Run: node scripts/gen-pdf-assets.mjs
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const night = { r: 7, g: 17, b: 13 };
async function jpeg(src, bg, width) {
  const { data, info } = await sharp(src)
    .resize({ width })
    .flatten({ background: bg })
    .jpeg({ quality: 88 })
    .toBuffer({ resolveWithObject: true });
  return { b64: data.toString("base64"), w: info.width, h: info.height };
}
const onNight = await jpeg("public/brand/lockup-white.png", night, 640);
const onWhite = await jpeg("public/brand/lockup-ink.png", { r: 255, g: 255, b: 255 }, 480);
const out = `// Generated by scripts/gen-pdf-assets.mjs from public/brand. Do not edit.
export const LOCKUP_ON_NIGHT = { w: ${onNight.w}, h: ${onNight.h}, b64: "${onNight.b64}" };
export const LOCKUP_ON_WHITE = { w: ${onWhite.w}, h: ${onWhite.h}, b64: "${onWhite.b64}" };
`;
writeFileSync("src/lib/pdf-assets.ts", out);
console.log("ok", onNight.w, onNight.h, out.length);
